import Foundation

public struct DNSRejection: Equatable, Sendable {
    public let domain: String
    public let reason: String
}

/// Which DNS zones Warren must answer for, derived from the registered sites' domains.
public struct DNSPlan: Sendable {
    public let zones: [String]
    /// Domains that need no DNS work, such as `*.localhost`, which macOS already resolves.
    public let native: [String]
    public let rejected: [DNSRejection]
    public let corefile: String
}

public enum DNSError: Error, Equatable, LocalizedError, Sendable {
    case invalidPort(Int)
    case notInstalled
    case noZones
    case portInUse(port: Int, holder: String?)
    case foreignResolverFile(String)
    case resolverCommandFailed

    public var errorDescription: String? {
        switch self {
        case let .invalidPort(port): "port \(port) is out of range (1 to 65535)"
        case .notInstalled: "CoreDNS is not installed. Run: warren dns install"
        case .noZones: "no registered domain needs DNS (only *.localhost, which macOS resolves itself, or none at all)"
        case let .portInUse(port, holder): "port \(port) is already in use" + (holder.map { " by \($0)" } ?? "")
        case let .foreignResolverFile(path):
            "\(path) already exists and is not managed by Warren. Warren will not change it; remove or rename it first."
        case .resolverCommandFailed: "writing the resolver files failed"
        }
    }
}

public enum DNSPlanner {
    public static let defaultPort = 5354

    /// TLDs reserved for local use, so one zone for the whole TLD is safe.
    static let reservedTLDs: Set = ["test", "internal"]

    public static func plan(domains: [String], port: Int) throws -> DNSPlan {
        guard (1 ... 65535).contains(port) else { throw DNSError.invalidPort(port) }

        var candidates: Set<String> = []
        var native: [String] = []
        var rejected: [DNSRejection] = []
        for domain in Set(domains).sorted() {
            switch domain.split(separator: ".").last.map(String.init) {
            case "localhost": native.append(domain)
            case "local":
                rejected.append(DNSRejection(
                    domain: domain,
                    reason: ".local is reserved for Bonjour; use .test instead"
                ))
            case let tld? where reservedTLDs.contains(tld): candidates.insert(tld)
            default: candidates.insert(domain)
            }
        }
        let zones = candidates.filter { zone in
            !candidates.contains { $0 != zone && zone.hasSuffix(".\($0)") }
        }.sorted()
        return DNSPlan(zones: zones, native: native, rejected: rejected, corefile: corefile(zones: zones, port: port))
    }

    /// CoreDNS configuration: loopback only, A and AAAA for each zone and its subdomains, nothing else.
    /// Names outside the zones get REFUSED, so Warren never answers for a real domain it was not asked about.
    static func corefile(zones: [String], port: Int) -> String {
        var blocks = ["# Generated by Warren. Changes are overwritten."]
        for (index, zone) in zones.enumerated() {
            var lines = [
                "\(zone):\(port) {",
                "    bind 127.0.0.1 ::1",
                "    template IN A {",
                "        answer \"{{ .Name }} 60 IN A 127.0.0.1\"",
                "    }",
                "    template IN AAAA {",
                "        answer \"{{ .Name }} 60 IN AAAA ::1\"",
                "    }",
            ]
            if index == 0 {
                lines.append("    reload 2s")
            }
            lines.append("}")
            blocks.append(lines.joined(separator: "\n"))
        }
        return blocks.joined(separator: "\n\n") + "\n"
    }
}

public extension WarrenPaths {
    var dnsCorefile: URL {
        runDirectory.appendingPathComponent("Corefile")
    }
}
